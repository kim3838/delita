    public function run($all = false, $debug = false): string
    {
        $this->testAll = $all;
        $passed = 0;
        $failed = 0;

        foreach ($this->testCases() as $testCase){

            if(!$testCase['test'])continue;

            $payloadMap = [
                Compensation::BASIC_PAY->value => 'BASICPAY',
                Compensation::REGULAR_ALLOWANCE->value => ['MEAL'],
                Compensation::OVERTIME->value => 'OVERTIME',
                Compensation::LEAVE_PAY->value => 'LEAVE-PAY',
                Compensation::HOLIDAY_PAY->value => 'HOLIDAY-PAY',
            ];
            $assignedEarningsPayload = $testCase['assigned_earnings'];
            $globalEarningsPayload = $testCase['global_earnings'];

            $this->workSplits = array_map(function($split){
                return [
                    'split_duration' => BigDecimal::of((string)$split['split_duration']),
                    'work_hour_type' => $split['work_hour_type'],
                    'regular_rate_multiplier' => BigDecimal::of((string)$split['regular_rate_multiplier']),
                    'non_rest_rate_multiplier' => BigDecimal::of((string)$split['non_rest_rate_multiplier']),
                    'hourly_rate_multiplier' => BigDecimal::of((string)$split['hourly_rate_multiplier']),
                    'base_rate_multiplier' => BigDecimal::of((string)$split['base_rate_multiplier']),
                    'actual_present' => BigDecimal::of((string)$split['actual_present']),
                ];
            },$testCase['work_splits']);
            $this->overtimeSplits = array_map(function($split){
                return [
                    'split_duration' => BigDecimal::of((string)$split['split_duration']),
                    'work_hour_type' => $split['work_hour_type'],
                    'regular_rate_multiplier' => BigDecimal::of((string)$split['regular_rate_multiplier']),
                    'non_rest_rate_multiplier' => BigDecimal::of((string)$split['non_rest_rate_multiplier']),
                    'hourly_rate_multiplier' => BigDecimal::of((string)$split['hourly_rate_multiplier']),
                    'base_rate_multiplier' => BigDecimal::of((string)$split['base_rate_multiplier']),
                    'actual_present' => BigDecimal::of((string)$split['actual_present']),
                ];
            },$testCase['overtime_splits']);
            $this->restDays = $testCase['rest_days'];

            $splitResults = $this->statementAttendanceSetAmountableOnSplits(
                $testCase['salary_statement_attendance'],
                $payloadMap,
                $assignedEarningsPayload,
                $globalEarningsPayload,
                true,
                false
            );

            $assignedCompensationsPatchable = collect($assignedEarningsPayload)->map(fn($value, $key) => [
                'formulable_type' => Formulable::EARNINGS->value,
                'component_type' => $value['component_type'],
                'component_name' => $value['component_name'],
                'work_hour_type' => $value['work_hour_type'],
                'regular_pay' => (string)$value['regular_pay'],
                'night_differential_pay' => (string)$value['night_differential_pay'],
                'rest_day_pay' => (string)$value['rest_day_pay'],
                'total' => (string)$value['total'],
            ])->values()->toArray();
            $globalCompensationsPatchable = collect($globalEarningsPayload)->map(fn($value, $key) => [
                'formulable_type' => Formulable::EARNINGS->value,
                'component_type' => $value['component_type'],
                'component_name' => $value['component_name'],
                'work_hour_type' => $value['work_hour_type'],
                'regular_pay' => (string)$value['regular_pay'],
                'night_differential_pay' => (string)$value['night_differential_pay'],
                'rest_day_pay' => (string)$value['rest_day_pay'],
                'total' => (string)$value['total'],
            ])->values()->toArray();
            $attendancePayItemsPatchable = array_merge($assignedCompensationsPatchable, $globalCompensationsPatchable);

            if(
                $testCase['expected']['pay_items'] == $attendancePayItemsPatchable &&
                $testCase['expected']['split_results'] == $splitResults
            ){
                $passed++;
            } else {
                $failed++;

                _debug([
                    'Test case failed' => $testCase['test_case'],
                ]);
            }
        }

        return sprintf('%d/%d', $passed, $passed + $failed);
    }
